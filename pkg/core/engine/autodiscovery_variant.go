package engine

import (
	"fmt"
	"strings"

	"dario.cat/mergo"
	"github.com/updatecli/updatecli/pkg/core/log"
	"github.com/updatecli/updatecli/pkg/core/pipeline"
	"github.com/updatecli/updatecli/pkg/core/pipeline/action"
	"github.com/updatecli/updatecli/pkg/core/pipeline/autodiscovery"
)

const (
	// defaultVariantGroup names, in pipeline IDs, the dependencies matching no autodiscovery group.
	defaultVariantGroup = "default"

	// groupLabel and versionFilterLabel are the labels set on pipelines generated for a group or a version filter.
	// The "updatecli.io/" prefix keeps them apart from the labels users set.
	groupLabel         = "updatecli.io/group"
	versionFilterLabel = "updatecli.io/versionfilter"
)

// variantPipelineID returns the pipeline ID shared by the pipelines generated for a variant.
// Without "groups" and "versionfilters" it's the autodiscovery pipeline ID, as before they existed.
func variantPipelineID(parentID, crawlerKind string, variant autodiscovery.Variant) string {
	if variant.IsDefault() {
		return parentID
	}

	parts := []string{parentID, variantKindSegment(crawlerKind), variantGroup(variant)}
	if variant.VersionFilter != "" {
		parts = append(parts, variant.VersionFilter)
	}

	return strings.Join(parts, "/")
}

// variantLabels returns the labels identifying the group and version filter of a generated pipeline.
func variantLabels(variant autodiscovery.Variant) map[string]string {
	labels := map[string]string{}

	if variant.Group != "" {
		labels[groupLabel] = variant.Group
	}

	if variant.VersionFilter != "" {
		labels[versionFilterLabel] = variant.VersionFilter
	}

	return labels
}

// withVariantLabels adds the variant labels to the labels of a generated pipeline.
// They identify the group and version filter of the pipeline, so they replace any label with the same key,
// such as one set on the autodiscovery manifest, with a warning.
func withVariantLabels(labels map[string]string, variant autodiscovery.Variant, pipelineName string) map[string]string {
	for k, v := range variantLabels(variant) {
		if labels == nil {
			labels = make(map[string]string)
		}

		if existing, ok := labels[k]; ok && existing != v {
			log.Warningf("Label %q set to %q in pipeline %q is replaced by %q, the value autodiscovery sets for its groups and versionfilters",
				k,
				existing,
				pipelineName,
				v)
		}

		labels[k] = v
	}

	return labels
}

// variantTitleSuffix returns the text added to action titles and pipeline names, such as "(golang, aws, major)".
//
// Grouped variants open one pull request per crawler, as their pipeline ID includes the crawler kind,
// so the kind is added to tell them apart. Individual pipelines are already named after their dependency.
func variantTitleSuffix(crawlerKind string, variant autodiscovery.Variant) string {
	if variant.IsDefault() {
		return ""
	}

	var parts []string

	if variant.GroupBy == autodiscovery.GROUPBYALL || variant.GroupBy == "" {
		parts = append(parts, crawlerKind)
	}

	if variant.Group != "" {
		parts = append(parts, variant.Group)
	}

	if variant.VersionFilter != "" {
		parts = append(parts, variant.VersionFilter)
	}

	if len(parts) == 0 {
		return ""
	}

	return fmt.Sprintf("(%s)", strings.Join(parts, ", "))
}

// variantGate returns how a generated pipeline is ordered against the other version filters, or nil without "versionfilters".
//
// Grouped pipelines share one pull request, so they wait for the whole group.
// Individual pipelines wait for the same dependency, which crawlers name the same way for every version filter.
func variantGate(parentManifestID, crawlerKind string, variant autodiscovery.Variant, groupBy autodiscovery.GroupBy, manifestName string) *pipeline.Gate {
	if variant.VersionFilter == "" {
		return nil
	}

	key := strings.Join([]string{parentManifestID, variantKindSegment(crawlerKind), variantGroup(variant)}, "/")
	if groupBy == autodiscovery.GROUPBYINDIVIDUAL {
		key += "/" + manifestName
	}

	return &pipeline.Gate{
		Key:           key,
		Rank:          variant.Rank,
		VersionFilter: variant.VersionFilter,
	}
}

// generatedActionConfig returns the action of a pipeline generated by autodiscovery.
//
// The autodiscovery action takes precedence over the action set by the crawler.
// Pipelines grouped with "groupby: all" share one pull request, so they need a stable title: groupedTitle.
// The group and version filter are added to the title, so pull requests updating the same dependencies can be told apart.
// Without any title, it's added to manifestName, which is otherwise the title used for the pull request.
func generatedActionConfig(autodiscoveryAction, crawlerAction action.Config, crawlerKind string, variant autodiscovery.Variant, groupedTitle func() string, manifestName string) action.Config {
	generated := autodiscoveryAction

	if (variant.GroupBy == autodiscovery.GROUPBYALL || variant.GroupBy == "") && generated.Title == "" {
		generated.Title = groupedTitle()
	}

	if err := mergo.Merge(&generated, crawlerAction); err != nil {
		log.Errorf("merging autodiscovery action: %s", err)
	}

	if suffix := variantTitleSuffix(crawlerKind, variant); suffix != "" {
		if generated.Title == "" {
			generated.Title = manifestName
		}
		generated.Title = strings.TrimSpace(generated.Title + " " + suffix)
	}

	return generated
}

// variantKindSegment returns the crawler kind as one segment of a pipeline ID or gate key.
//
// Kinds such as "golang/gomod" contain a "/", which group and version filter names can't,
// so without this "golang" with group "gomod" and filter "aws" would share an ID with "golang/gomod" with group "aws".
// No crawler kind contains a "-", and WASM plugins don't support variants, so two kinds never get the same segment.
func variantKindSegment(crawlerKind string) string {
	return strings.ReplaceAll(crawlerKind, "/", "-")
}

func variantGroup(variant autodiscovery.Variant) string {
	if variant.Group == "" {
		return defaultVariantGroup
	}
	return variant.Group
}
